import { chromium } from '@playwright/test';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:3000/animated-login.html');
await page.locator('canvas[data-ready="true"]').waitFor();
assert.equal(await page.locator('#photo img').count(), 0);
assert.equal(await page.locator('#mascot .robot').count(), 0);
await page.screenshot({ path: 'test-results/photo-login-mobile.png', fullPage: true });
await page.locator('#full-name').focus();
assert.equal(await page.locator('#mascot').getAttribute('data-mood'), 'curious');
await page.locator('#email').focus();
assert.equal(await page.locator('#bubble').textContent(), 'Enter your email address 📧');
await page.locator('#password').fill('secret123');
assert.equal(await page.locator('#mascot').getAttribute('data-mood'), 'shy');
assert.match(await page.locator('#photo').getAttribute('aria-label'), /covering its eyes/);
await page.locator('#toggle-password').click();
assert.equal(await page.locator('#password').getAttribute('type'), 'text');
await page.locator('#submit-button').click();
assert.equal(await page.locator('#mascot').getAttribute('data-mood'), 'sad');
assert.equal(await page.locator('[aria-invalid=true]').count(), 2);
await page.locator('#full-name').fill('Usman Shams');
await page.locator('#email').fill('usman@company.com');
await page.locator('#submit-button').click();
assert.equal(await page.locator('#mascot').getAttribute('data-mood'), 'joyful');
assert.equal(await page.locator('.confetti-bit').count(), 44);
await page.getByRole('tab', { name: 'Sign In', exact: true }).click();
assert(await page.locator('#name-label').isHidden());
assert.equal(await page.locator('#password').inputValue(), '');
await page.getByRole('tab', { name: 'Sign In', exact: true }).press('ArrowLeft');
assert.equal(await page.locator('#register-tab').getAttribute('aria-selected'), 'true');
for (const width of [320, 390, 1440]) {
  await page.setViewportSize({ width, height: 900 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
}
await page.screenshot({ path: 'test-results/photo-login-desktop.png', fullPage: true });
await page.emulateMedia({ reducedMotion: 'reduce' });
assert.equal(await page.locator('#photo').evaluate(el => getComputedStyle(el).animationName), 'none');
assert.deepEqual(errors, []);
console.log('PASS: animated kitten canvas, paw privacy pose, focus moods, validation, visibility, celebration, tabs, 320/390/1440 layouts, reduced motion; no JS errors.');
await browser.close();
